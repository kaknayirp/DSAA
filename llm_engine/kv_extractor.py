"""
KV Cache Extraction and Inspection Utilities for DSAA.

Module Owner: Person 1 — LLM & KV Cache Engineer.

This module provides tools to extract, inspect, and calculate memory consumption
for Key-Value (KV) Caches generated by autoregressive language models.

Supports:
- Hugging Face `DynamicCache` (Transformers >= 4.36)
- Legacy tuple of tuples: ((key_0, value_0), (key_1, value_1), ...)
- List of tuples / custom cache containers
- Memory calculation in bytes, KB, and MB (logical and actual storage)
- Grouped Query Attention (GQA) detection and tensor layout analysis
- Non-destructive inspection
"""

import logging
from dataclasses import dataclass, asdict, field
from typing import Any, Dict, List, Optional, Tuple, Union

from .exceptions import LLMEngineError

logger = logging.getLogger(__name__)

# Standard byte size mappings for common deep learning data types
DTYPE_ELEMENT_SIZES: Dict[str, int] = {
    "float32": 4,
    "torch.float32": 4,
    "float": 4,
    "float16": 2,
    "torch.float16": 2,
    "half": 2,
    "bfloat16": 2,
    "torch.bfloat16": 2,
    "int8": 1,
    "torch.int8": 1,
    "uint8": 1,
    "torch.uint8": 1,
    "int16": 2,
    "torch.int16": 2,
    "int32": 4,
    "torch.int32": 4,
    "int64": 8,
    "torch.int64": 8,
    "long": 8,
    "float64": 8,
    "torch.float64": 8,
    "double": 8,
}


class KVCacheInspectionError(LLMEngineError):
    """Raised when an invalid, corrupt, or unsupported KV Cache is inspected."""
    pass


@dataclass
class TensorStats:
    """Detailed memory and shape statistics for an individual Key or Value tensor."""
    shape: Tuple[int, ...]
    dtype: str
    device: str
    numel: int
    element_size_bytes: int
    logical_bytes: int
    storage_bytes: Optional[int] = None
    is_contiguous: Optional[bool] = None

    @property
    def logical_kb(self) -> float:
        return self.logical_bytes / 1024.0

    @property
    def logical_mb(self) -> float:
        return self.logical_bytes / (1024.0 * 1024.0)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "shape": list(self.shape),
            "dtype": self.dtype,
            "device": self.device,
            "numel": self.numel,
            "element_size_bytes": self.element_size_bytes,
            "logical_bytes": self.logical_bytes,
            "logical_kb": round(self.logical_kb, 4),
            "logical_mb": round(self.logical_mb, 4),
            "storage_bytes": self.storage_bytes,
            "is_contiguous": self.is_contiguous,
        }


@dataclass
class LayerCacheStats:
    """Statistics for the Key and Value tensors of a single transformer layer."""
    layer_idx: int
    key: TensorStats
    value: TensorStats

    @property
    def total_bytes(self) -> int:
        return self.key.logical_bytes + self.value.logical_bytes

    @property
    def total_kb(self) -> float:
        return self.total_bytes / 1024.0

    @property
    def total_mb(self) -> float:
        return self.total_bytes / (1024.0 * 1024.0)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "layer_idx": self.layer_idx,
            "key": self.key.to_dict(),
            "value": self.value.to_dict(),
            "total_bytes": self.total_bytes,
            "total_kb": round(self.total_kb, 4),
            "total_mb": round(self.total_mb, 4),
        }


@dataclass
class CacheReport:
    """
    Comprehensive structured report of KV Cache state across all transformer layers.
    Non-destructively extracted from model output.
    """
    cache_type: str
    num_layers: int
    batch_size: int
    num_kv_heads: int
    seq_len: int
    head_dim: int
    dtype: str
    device: str
    total_bytes: int
    total_kb: float
    total_mb: float
    actual_storage_bytes: int
    actual_storage_mb: float
    layers: List[LayerCacheStats] = field(default_factory=list)
    is_shared_storage: bool = False
    is_gqa: bool = False
    tensor_layout: str = "batch_size x num_kv_heads x seq_len x head_dim"

    def to_dict(self) -> Dict[str, Any]:
        """Convert report to dictionary for serialization or evaluation logging."""
        return {
            "cache_type": self.cache_type,
            "num_layers": self.num_layers,
            "batch_size": self.batch_size,
            "num_kv_heads": self.num_kv_heads,
            "seq_len": self.seq_len,
            "head_dim": self.head_dim,
            "dtype": self.dtype,
            "device": self.device,
            "total_bytes": self.total_bytes,
            "total_kb": round(self.total_kb, 4),
            "total_mb": round(self.total_mb, 4),
            "actual_storage_bytes": self.actual_storage_bytes,
            "actual_storage_mb": round(self.actual_storage_mb, 4),
            "is_shared_storage": self.is_shared_storage,
            "is_gqa": self.is_gqa,
            "tensor_layout": self.tensor_layout,
            "layers": [layer.to_dict() for layer in self.layers],
        }

    def summary_table(self) -> str:
        """Generate human-readable summary text."""
        lines = [
            "================================================================================",
            "                        DSAA KV CACHE INSPECTION REPORT                         ",
            "================================================================================",
            f" Cache Type:           {self.cache_type}",
            f" Total Layers:         {self.num_layers}",
            f" Batch Size:           {self.batch_size}",
            f" KV Heads per Layer:   {self.num_kv_heads}{' (Grouped Query Attention)' if self.is_gqa else ''}",
            f" Sequence Length:      {self.seq_len}",
            f" Head Dimension:       {self.head_dim}",
            f" Data Type:            {self.dtype}",
            f" Device:               {self.device}",
            f" Tensor Layout:        {self.tensor_layout}",
            "--------------------------------------------------------------------------------",
            f" Total Logical Memory: {self.total_bytes:,} bytes | {self.total_kb:,.2f} KB | {self.total_mb:,.4f} MB",
            f" Actual Storage Alloc: {self.actual_storage_bytes:,} bytes | {self.actual_storage_mb:,.4f} MB",
            f" Shared Storage:       {self.is_shared_storage}",
            "--------------------------------------------------------------------------------",
            " Layer Breakdown (Sample):",
        ]

        if not self.layers:
            lines.append("   (No layer data present)")
        else:
            # Show first layer, middle layer (if applicable), and last layer
            indices_to_show = [0]
            if len(self.layers) > 2:
                indices_to_show.append(len(self.layers) // 2)
            if len(self.layers) > 1:
                indices_to_show.append(len(self.layers) - 1)

            indices_to_show = sorted(list(set(indices_to_show)))
            for idx in indices_to_show:
                layer = self.layers[idx]
                lines.append(
                    f"   Layer {layer.layer_idx:2d}: "
                    f"Key shape {str(layer.key.shape):<20} "
                    f"Val shape {str(layer.value.shape):<20} "
                    f"Layer Mem: {layer.total_kb:,.2f} KB ({layer.total_bytes:,} B)"
                )

            if len(self.layers) > len(indices_to_show):
                lines.append(f"   ... ({len(self.layers) - len(indices_to_show)} intermediate layers omitted for brevity)")

        lines.append("================================================================================")
        return "\n".join(lines)


def get_tensor_element_size(tensor: Any) -> int:
    """
    Determine the element size in bytes of a tensor or array.
    Supports PyTorch tensors, NumPy arrays, and duck-typed objects.
    """
    if hasattr(tensor, "element_size"):
        try:
            return tensor.element_size()
        except Exception:
            pass

    if hasattr(tensor, "itemsize"):
        try:
            return tensor.itemsize
        except Exception:
            pass

    # Fallback to dtype string lookup
    dtype_str = str(getattr(tensor, "dtype", "float32")).lower()
    for key, size in DTYPE_ELEMENT_SIZES.items():
        if key in dtype_str:
            return size

    return 4  # Default to 4 bytes (float32)


def get_tensor_storage_info(tensor: Any) -> Tuple[Optional[int], Optional[int]]:
    """
    Extract physical storage pointer and allocated storage size if available.
    Returns (data_ptr, storage_nbytes).
    """
    storage = None
    if hasattr(tensor, "untyped_storage"):
        try:
            storage = tensor.untyped_storage()
        except Exception:
            pass
    elif hasattr(tensor, "storage"):
        try:
            storage = tensor.storage()
        except Exception:
            pass

    if storage is not None:
        try:
            ptr = storage.data_ptr() if hasattr(storage, "data_ptr") else None
            nbytes = storage.nbytes() if hasattr(storage, "nbytes") else None
            return ptr, nbytes
        except Exception:
            pass

    return None, None


def inspect_tensor(tensor: Any) -> TensorStats:
    """
    Extract non-destructive shape, dtype, device, and memory metadata for a single tensor.
    """
    if tensor is None:
        raise KVCacheInspectionError("Cannot inspect None tensor.")

    shape = tuple(getattr(tensor, "shape", ()))
    dtype_str = str(getattr(tensor, "dtype", "unknown"))
    device_str = str(getattr(tensor, "device", "cpu"))

    if hasattr(tensor, "numel"):
        numel = tensor.numel()
    else:
        # Compute product of dimensions
        numel = 1
        for dim in shape:
            numel *= dim

    element_size = get_tensor_element_size(tensor)
    logical_bytes = numel * element_size

    storage_ptr, storage_bytes = get_tensor_storage_info(tensor)

    is_contiguous = None
    if hasattr(tensor, "is_contiguous"):
        try:
            is_contiguous = bool(tensor.is_contiguous())
        except Exception:
            pass

    return TensorStats(
        shape=shape,
        dtype=dtype_str,
        device=device_str,
        numel=numel,
        element_size_bytes=element_size,
        logical_bytes=logical_bytes,
        storage_bytes=storage_bytes,
        is_contiguous=is_contiguous,
    )


class KVCacheInspector:
    """
    Reusable, non-destructive inspector for extracting and analyzing LLM KV Caches.
    Supports Hugging Face `DynamicCache`, legacy tuples, and custom lists.
    """

    @classmethod
    def extract_layers(cls, past_key_values: Any) -> Tuple[str, List[Tuple[Any, Any]]]:
        """
        Normalize various cache representations into a uniform list of (key_tensor, value_tensor) pairs.

        Returns:
            Tuple of (cache_type_name, list_of_layer_kv_tuples)
        """
        if past_key_values is None:
            raise KVCacheInspectionError("past_key_values is None. Ensure 'use_cache=True' was enabled during forward pass.")

        # 1. Hugging Face DynamicCache (Transformers >= 4.36)
        if hasattr(past_key_values, "key_cache") and hasattr(past_key_values, "value_cache"):
            key_cache = past_key_values.key_cache
            value_cache = past_key_values.value_cache
            if len(key_cache) != len(value_cache):
                raise KVCacheInspectionError(
                    f"DynamicCache mismatch: len(key_cache)={len(key_cache)} != len(value_cache)={len(value_cache)}"
                )
            pairs = [(key_cache[i], value_cache[i]) for i in range(len(key_cache))]
            return "DynamicCache", pairs

        # 2. Tuple of tuples or List of tuples
        if isinstance(past_key_values, (tuple, list)):
            if len(past_key_values) == 0:
                raise KVCacheInspectionError("Received an empty past_key_values collection (0 layers).")

            first_elem = past_key_values[0]
            if isinstance(first_elem, (tuple, list)) and len(first_elem) == 2:
                # Standard causal LM layout: ((k0, v0), (k1, v1), ...)
                pairs = [(layer[0], layer[1]) for layer in past_key_values]
                type_name = "tuple_of_tuples" if isinstance(past_key_values, tuple) else "list_of_tuples"
                return type_name, pairs

            # Encoder-decoder models sometimes store 4 tensors per layer (self_k, self_v, cross_k, cross_v)
            if isinstance(first_elem, (tuple, list)) and len(first_elem) == 4:
                pairs = [(layer[0], layer[1]) for layer in past_key_values]
                return "encoder_decoder_cache (self_attention)", pairs

        # 3. Object supporting layer indexing or length
        if hasattr(past_key_values, "__len__") and hasattr(past_key_values, "__getitem__"):
            try:
                pairs = []
                for i in range(len(past_key_values)):
                    item = past_key_values[i]
                    if isinstance(item, (tuple, list)) and len(item) == 2:
                        pairs.append((item[0], item[1]))
                    else:
                        break
                if len(pairs) == len(past_key_values):
                    return type(past_key_values).__name__, pairs
            except Exception:
                pass

        raise KVCacheInspectionError(
            f"Unsupported past_key_values representation: '{type(past_key_values).__name__}'. "
            f"Expected DynamicCache, tuple of tuples, or list of tuples."
        )

    def inspect(self, past_key_values: Any) -> CacheReport:
        """
        Analyze the provided KV Cache and return a comprehensive CacheReport.
        Does not mutate the cache or underlying tensors.
        """
        cache_type, layer_pairs = self.extract_layers(past_key_values)

        num_layers = len(layer_pairs)
        if num_layers == 0:
            raise KVCacheInspectionError("No layers found in the extracted cache.")

        layer_stats: List[LayerCacheStats] = []
        total_logical_bytes = 0
        seen_storage_ptrs = set()
        total_actual_storage_bytes = 0

        for layer_idx, (k_tensor, v_tensor) in enumerate(layer_pairs):
            k_stat = inspect_tensor(k_tensor)
            v_stat = inspect_tensor(v_tensor)

            layer_stat = LayerCacheStats(layer_idx=layer_idx, key=k_stat, value=v_stat)
            layer_stats.append(layer_stat)
            total_logical_bytes += layer_stat.total_bytes

            # Track unique physical storage allocations
            for stat, tensor in [(k_stat, k_tensor), (v_stat, v_tensor)]:
                ptr, s_nbytes = get_tensor_storage_info(tensor)
                if ptr is not None and s_nbytes is not None:
                    if ptr not in seen_storage_ptrs:
                        seen_storage_ptrs.add(ptr)
                        total_actual_storage_bytes += s_nbytes
                else:
                    # If physical storage cannot be queried, use logical bytes
                    total_actual_storage_bytes += stat.logical_bytes

        # Extract representative dimensions from layer 0
        ref_k = layer_stats[0].key
        ref_shape = ref_k.shape

        # Standard Hugging Face Causal LM Key/Value shape is 4D:
        # [batch_size, num_kv_heads, seq_len, head_dim]
        if len(ref_shape) == 4:
            batch_size, num_kv_heads, seq_len, head_dim = ref_shape
            tensor_layout = "batch_size x num_kv_heads x seq_len x head_dim"
        elif len(ref_shape) == 3:
            # Some custom architectures: [batch_size, seq_len, hidden_dim]
            batch_size, seq_len, head_dim = ref_shape
            num_kv_heads = 1
            tensor_layout = "batch_size x seq_len x head_dim"
        else:
            batch_size = ref_shape[0] if len(ref_shape) > 0 else 0
            seq_len = ref_shape[-2] if len(ref_shape) >= 2 else 0
            head_dim = ref_shape[-1] if len(ref_shape) >= 1 else 0
            num_kv_heads = ref_shape[1] if len(ref_shape) >= 3 else 1
            tensor_layout = f"custom_{len(ref_shape)}D"

        # Grouped Query Attention (GQA) heuristic:
        # In Qwen2.5-1.5B, num_kv_heads = 2 while num_attention_heads = 12.
        # Usually GQA models have num_kv_heads in {2, 4, 8} which is significantly smaller than hidden_size/head_dim.
        is_gqa = num_kv_heads > 0 and num_kv_heads < 8

        is_shared_storage = (
            len(seen_storage_ptrs) > 0 and len(seen_storage_ptrs) < (num_layers * 2)
        )

        total_kb = total_logical_bytes / 1024.0
        total_mb = total_logical_bytes / (1024.0 * 1024.0)
        actual_storage_mb = total_actual_storage_bytes / (1024.0 * 1024.0)

        return CacheReport(
            cache_type=cache_type,
            num_layers=num_layers,
            batch_size=batch_size,
            num_kv_heads=num_kv_heads,
            seq_len=seq_len,
            head_dim=head_dim,
            dtype=ref_k.dtype,
            device=ref_k.device,
            total_bytes=total_logical_bytes,
            total_kb=total_kb,
            total_mb=total_mb,
            actual_storage_bytes=total_actual_storage_bytes,
            actual_storage_mb=actual_storage_mb,
            layers=layer_stats,
            is_shared_storage=is_shared_storage,
            is_gqa=is_gqa,
            tensor_layout=tensor_layout,
        )


def extract_kv_cache(past_key_values: Any) -> CacheReport:
    """
    Convenience function to inspect past_key_values in one call.

    Args:
        past_key_values: KV Cache output from a model forward pass.

    Returns:
        Structured CacheReport.
    """
    inspector = KVCacheInspector()
    return inspector.inspect(past_key_values)


def run_inference_and_inspect_cache(
    model: Any,
    tokenizer: Any,
    prompt: str = "Explain how the KV Cache enables efficient autoregressive generation.",
    device: Optional[str] = None
) -> Tuple[Any, CacheReport]:
    """
    Integration helper to run a forward pass with the loaded model and inspect its KV Cache.

    Args:
        model: Pretrained Causal LM in eval mode.
        tokenizer: Pretrained Tokenizer.
        prompt: Text prompt to encode and evaluate.
        device: Device to place input tensors ('cuda', 'cpu', etc.). If None, inferred from model.

    Returns:
        Tuple of (model_outputs, CacheReport).
    """
    import torch

    if device is None:
        device = getattr(model, "device", "cpu")
        if isinstance(device, torch.device):
            device = str(device)

    # Encode prompt
    inputs = tokenizer(prompt, return_tensors="pt")
    input_ids = inputs["input_ids"].to(device)
    attention_mask = inputs.get("attention_mask")
    if attention_mask is not None:
        attention_mask = attention_mask.to(device)

    # Run forward pass with KV caching enabled
    with torch.no_grad():
        outputs = model(
            input_ids=input_ids,
            attention_mask=attention_mask,
            use_cache=True,
            return_dict=True,
        )

    if not hasattr(outputs, "past_key_values") or outputs.past_key_values is None:
        raise KVCacheInspectionError(
            "Model forward pass did not return 'past_key_values'. "
            "Verify that 'use_cache=True' is supported and active."
        )

    inspector = KVCacheInspector()
    report = inspector.inspect(outputs.past_key_values)
    return outputs, report
